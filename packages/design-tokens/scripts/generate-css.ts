import {
	controlLayout,
	controlSize,
	iconSize,
	fontWeight,
	lightColors,
	radius,
	spacing,
	typography,
	codeTypography,
	workspaceLayout,
} from "../src/tokens";

const variableName = (name: string): string =>
	name
		.replace(/([a-z])([A-Z0-9])/g, "$1-$2")
		.replaceAll(".", "-")
		.toLowerCase();

const pixelVariables = (
	prefix: string,
	values: Readonly<Record<string, number>>
): string[] =>
	Object.entries(values).map(
		([name, value]) => `\t--1git-${prefix}-${variableName(name)}: ${value}px;`
	);

const declarations = [
	...Object.entries(lightColors).map(
		([name, value]) => `\t--${variableName(name)}: ${value};`
	),
	...Object.entries(workspaceLayout).map(
		([name, value]) => `\t--${variableName(name)}: ${value}px;`
	),
	...Object.entries(typography).flatMap(([name, value]) => [
		`\t--1git-text-${name}: ${value.fontSize}px;`,
		`\t--1git-leading-${name}: ${value.lineHeight}px;`,
	]),
	...Object.entries(fontWeight).map(
		([name, value]) => `\t--1git-weight-${name}: ${value};`
	),
	...pixelVariables("space", spacing),
	...pixelVariables("radius", radius),
	...pixelVariables("icon", iconSize),
	...pixelVariables("control", controlSize),
	...Object.entries(controlLayout).flatMap(([density, values]) =>
		pixelVariables(density, values)
	),
	`\t--1git-code-size: ${codeTypography.fontSize}px;`,
	`\t--1git-code-leading: ${codeTypography.lineHeight}px;`,
	`\t--1git-code-font: ${codeTypography.fontFamily};`,
];

const css = `/* Generated by bun run --cwd packages/design-tokens generate. */\n:root {\n${declarations.join("\n")}\n}\n`;
const target = Bun.file(new URL("../src/light.css", import.meta.url));

if (process.argv.includes("--check")) {
	if (!(await target.exists()) || (await target.text()) !== css) {
		throw new Error(
			"Shared token CSS is stale. Run bun run --cwd packages/design-tokens generate."
		);
	}
} else {
	await Bun.write(target, css);
}
