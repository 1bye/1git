import { lightColors, workspaceLayout } from "../src/tokens";

const variableName = (name: string): string =>
	name.replace(/([a-z])([A-Z0-9])/g, "$1-$2").toLowerCase();
const declarations = [
	...Object.entries(lightColors).map(
		([name, value]) => `\t--${variableName(name)}: ${value};`
	),
	...Object.entries(workspaceLayout).map(
		([name, value]) => `\t--${variableName(name)}: ${value}px;`
	),
];
const css = `/* Generated by bun run --cwd packages/design-tokens generate. */\n:root {\n${declarations.join("\n")}\n}\n`;
const target = Bun.file(new URL("../src/light.css", import.meta.url));

if (process.argv.includes("--check")) {
	if (!(await target.exists()) || (await target.text()) !== css) {
		throw new Error(
			"Shared token CSS is stale. Run bun run --cwd packages/design-tokens generate."
		);
	}
} else {
	await Bun.write(target, css);
}
